"""Persona loading and diversity selection.

IN PLAIN WORDS
--------------
This makes the 36 PERSONALITIES.

Each pretend person comes from a small record -- a name, a job, an age, what
they are interested in. This file turns that record into the paragraph of
instructions the AI reads to "become" that person.

It also always picks the same 36 people in the same order every run. That
sounds boring but it is essential: it means person #7 is the same person in
every run, so runs can be fairly compared.

WHY THIS EXISTS
---------------
An interest-based feed can only tell people apart to the extent they actually
differ. Measured separability of the available sources (mean pairwise cosine
between persona texts -- lower is more distinguishable):

    reddit user_data_36, `bio` field      n=36   mean 0.829   spread 0.257
    reddit user_data_36, `persona` field  n=36   mean 0.963   spread 0.170
    twitter False_Business_0, `user_char` n=99   mean 0.690   spread 0.493

Two things follow. First, the reddit `persona` texts -- the ones fed into the
system prompt -- are 0.963 similar to one another, so those agents were given
near-identical characters to play. Second, the twitter set is dramatically more
varied, because they are real scraped bios rather than generated ones:

    "Lecturer in Healthcare Marketing and Commercialisation at UCL"
    "I dance on tiktok, and cry in bed"
    "Cook.Ride.Explore."

The twitter file has 99 usable rows, which is more agents than a local 8B model
can run in reasonable time. Rather than take the first N -- which inherits
whatever ordering the file happens to have -- `select_diverse` picks a subset
that maximises the minimum distance between members, so a 36-agent run covers
as much of the population as 36 agents can.

The trade-off is stated honestly: twitter rows carry no age, gender, MBTI,
country or profession, so those disappear from the prompt. What they gain is
separability, which is the thing personalisation actually depends on.
"""

from __future__ import annotations

import json
import os


def _clean(x, fallback=""):
    """Tidy up a piece of persona text before it goes into the prompt."""
    s = ("" if x is None else str(x)).strip()
    return s if s and s.lower() != "nan" else fallback


def load_reddit(path):
    """OASIS's generated persona file: 10 structured fields per record."""
    out = []
    for e in json.load(open(path)):
        out.append({
            "username": e["username"],
            "realname": e.get("realname"),
            "bio": e.get("bio") or "",
            "persona": e.get("persona") or "",
            "age": e.get("age"), "gender": e.get("gender"),
            "mbti": e.get("mbti"), "country": e.get("country"),
            "profession": e.get("profession"),
            "interested_topics": e.get("interested_topics") or [],
            "source": "reddit_generated",
        })
    return out


def load_twitter(path):
    """Scraped Twitter profiles: real bios, no structured demographics.

    `previous_tweets` is deliberately NOT imported as posts. Every post in a
    run must be generated by the model during that run (D-6); importing real
    tweets would put content in the simulation that no agent wrote.
    """
    import pandas as pd

    df = pd.read_csv(path)
    out = []
    for i, row in df.iterrows():
        char = _clean(row.get("user_char"))
        desc = _clean(row.get("description"))
        if not (char or desc):
            continue
        uname = _clean(row.get("username")) or f"user{i}"
        out.append({
            "username": uname,
            "realname": _clean(row.get("name")) or uname,
            # The recommender ranks on `bio`; the prompt leads with `persona`.
            # Both are populated from the richest text available.
            "bio": char or desc,
            "persona": desc or char,
            "age": None, "gender": None, "mbti": None, "country": None,
            "profession": None, "interested_topics": [],
            "source": "twitter_scraped",
        })
    return out


_STOP = {
    "the", "and", "for", "with", "that", "this", "you", "your", "our", "are",
    "all", "was", "not", "but", "have", "has", "from", "they", "their", "who",
    "what", "when", "where", "how", "why", "can", "will", "just", "about",
    "into", "out", "get", "got", "one", "two", "new", "now", "here", "there",
    "more", "most", "some", "any", "than", "then", "them", "his", "her",
    "she", "him", "its", "it's", "i'm", "i've", "don't", "user",
}


def make_handle(persona, taken):
    """A readable, digit-free handle derived from the persona's own words.

    Finding F-20. The scraped personas ship as `user0`..`user110`, and agents
    read the digits out of the handle and passed them as ids: `follow(46)` for
    `user46`. Measured in the v5 run -- 230 rejected follows aimed at id 46,
    136 at 44, 126 at 96, all matching handles present in the feed. Follows
    fell from 90 to 53 because those guesses were finally being caught rather
    than silently entering the graph.

    Handles from the anonymised source carry no information anyway, so they are
    replaced with something drawn from the persona's own text: no digits for a
    model to mistake for an id, and a name that actually says who this is,
    which the raw `user46` never did.
    """
    import re

    text = " ".join(str(persona.get(f) or "")
                    for f in ("bio", "persona", "profession"))
    raw = [w.lower() for w in re.findall(r"[A-Za-z][A-Za-z']{2,}", text)]
    # Dedupe first: a word repeated in the bio would otherwise pair with
    # itself and produce handles like "mainstream_mainstream".
    seen, words = set(), []
    for w in raw:
        if w in _STOP or w in seen or not w.isalpha():
            continue
        seen.add(w)
        words.append(w)

    # Longer words are more distinctive; ties keep source order so the result
    # is deterministic.
    words.sort(key=lambda w: -len(w))
    pick = words[:6]

    for i in range(len(pick)):
        for j in range(i + 1, len(pick)):
            cand = f"{pick[i][:12]}_{pick[j][:10]}"
            if cand not in taken:
                return cand
    for w in pick:
        if w not in taken:
            return w
    n = len(taken)
    base = "".join(chr(ord("a") + (n // (26 ** k)) % 26) for k in (2, 1, 0))
    return f"anon_{base}"


def assign_handles(personas):
    """Give every persona a unique, digit-free handle (F-20)."""
    taken, out = set(), []
    for p in personas:
        h = make_handle(p, taken)
        taken.add(h)
        q = dict(p)
        q["source_username"] = p.get("username")
        q["username"] = h
        out.append(q)
    return out


def load_personas(path, rename_numeric=True):
    """Load personas, replacing digit-bearing handles by default (F-20).

    Reddit personas already have meaningful handles (`millerhospitality`) and
    are left alone; only handles that look like ids get replaced.
    """
    import re

    people = load_twitter(path) if str(path).endswith(".csv") \
        else load_reddit(path)
    if rename_numeric and any(re.search(r"\d", str(p.get("username") or ""))
                              for p in people):
        people = assign_handles(people)
    return people


def select_diverse(personas, k, field="bio"):
    """Greedy max-min selection: repeatedly take the persona furthest from
    everything already chosen.

    Taking the first k rows would inherit the file's ordering, which may
    cluster. This spreads the sample across the population instead. Seeded by
    the single most unusual persona (the one least like the average) so the
    result is deterministic and does not depend on RNG.
    """
    if k >= len(personas):
        return personas

    from embedding import cosine_matrix, embed

    texts = [p.get(field) or p.get("persona") or "" for p in personas]
    vecs = embed(texts)
    sim = cosine_matrix(vecs, vecs)

    n = len(personas)
    avg = [sum(float(sim[i, j]) for j in range(n) if j != i) / (n - 1)
           for i in range(n)]
    chosen = [min(range(n), key=lambda i: avg[i])]

    while len(chosen) < k:
        best, best_score = None, 2.0
        for i in range(n):
            if i in chosen:
                continue
            # Distance to the nearest already-chosen persona; maximise it.
            worst = max(float(sim[i, c]) for c in chosen)
            if worst < best_score:
                best, best_score = i, worst
        if best is None:
            break
        chosen.append(best)
    return [personas[i] for i in chosen]


def describe(personas, field="bio"):
    """Report separability so any personalisation claim can be read against
    the ceiling this population imposes."""
    import statistics

    from embedding import cosine_matrix, embed

    texts = [p.get(field) or "" for p in personas]
    vecs = embed(texts)
    sim = cosine_matrix(vecs, vecs)
    n = len(personas)
    off = [float(sim[i, j]) for i in range(n) for j in range(n) if i != j]
    return {
        "n": n,
        "source": personas[0].get("source") if personas else None,
        "field": field,
        "mean_similarity": round(statistics.mean(off), 4),
        "min": round(min(off), 4),
        "max": round(max(off), 4),
        "spread": round(max(off) - min(off), 4),
    }


if __name__ == "__main__":
    import sys
    src = sys.argv[1] if len(sys.argv) > 1 else \
        "data/twitter_dataset/anonymous_topic_200_1h/False_Business_0.csv"
    k = int(sys.argv[2]) if len(sys.argv) > 2 else 36
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    ps = load_personas(src)
    print("all      :", describe(ps))
    sub = select_diverse(ps, k)
    print("diverse  :", describe(sub))
    print("first-k  :", describe(ps[:k]))
    for p in sub[:6]:
        print("   ", p["username"], "|", p["bio"][:80])
